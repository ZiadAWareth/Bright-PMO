/** The page of one record, or null when this app has no pages for that table. */
export function recordPath(entityName?: string | null, id?: string | number | null): string | null {
  if (!entityName || id == null || String(id).trim() === '') return null;
  const base = RECORD_ROUTES[String(entityName).toLowerCase()];
  return base ? `${base}/${encodeURIComponent(String(id).trim())}` : null;
}
